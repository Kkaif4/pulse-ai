"use client";

import React from "react";
import { Trade } from "../../types";
import { HistoricalTradesTable } from "../HistoricalTradesTable";
import { TableSkeleton } from "../common/Skeletons";
import { CalendarIcon, FolderIcon } from "../common/Icons";

interface HistoryViewProps {
  historyDate: string;
  maxDate: string;
  historyTrades: Trade[];
  historyLoading: boolean;
  onDateChange: (date: string) => void;
  onSelectTrade: (trade: Trade) => void;
  onDeleteTrade: (id: number) => void;
}

export function HistoryView({
  historyDate,
  maxDate,
  historyTrades,
  historyLoading,
  onDateChange,
  onSelectTrade,
  onDeleteTrade,
}: HistoryViewProps) {
  return (
    <div className="rounded-xl border border-zinc-900 bg-zinc-900/20 p-6 space-y-6">
      <div className="flex flex-col sm:flex-row sm:items-center sm:justify-between gap-4 border-b border-zinc-900 pb-5">
        <div className="flex items-center gap-2.5">
          <CalendarIcon className="w-5 h-5 text-cyan-400" />
          <div>
            <h3 className="text-lg font-bold tracking-tight text-white">Historical Trade Lookup</h3>
            <p className="text-xs text-zinc-500 mt-0.5">
              Review market cycle ticks generated by the pulseAI Engine on any specific calendar date
            </p>
          </div>
        </div>

        <div className="flex items-center gap-3">
          <span className="text-xs font-semibold text-zinc-400">Select Date:</span>
          <input
            type="date"
            value={historyDate}
            max={maxDate}
            onChange={(e) => onDateChange(e.target.value)}
            className="rounded-lg border border-zinc-800 bg-zinc-950 px-3 py-1.5 text-sm text-white focus:border-cyan-500 focus:outline-none focus:ring-1 focus:ring-cyan-500 font-medium font-mono"
          />
        </div>
      </div>

      {historyLoading ? (
        <TableSkeleton rows={10} />
      ) : historyTrades.length === 0 ? (
        <div className="text-center py-20 rounded-xl border border-dashed border-zinc-900 bg-zinc-950/20">
          <FolderIcon className="w-10 h-10 text-zinc-600 mx-auto mb-3" />
          <span className="text-sm font-semibold text-zinc-400 block">
            No trading logs found for {new Date(historyDate).toLocaleDateString()}
          </span>
          <p className="text-xs text-zinc-600 mt-1">The market may have been closed, or the engine was not running.</p>
        </div>
      ) : (
        <HistoricalTradesTable
          historyTrades={historyTrades}
          setSelectedHistoryTrade={onSelectTrade}
          onDeleteTrade={onDeleteTrade}
        />
      )}
    </div>
  );
}
